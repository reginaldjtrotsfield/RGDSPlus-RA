/* Stage 2 frame hook                                                        */
/* ------------------------------------------------------------------------- */

static uintptr_t decode_branch_target(
    uintptr_t from,
    uint32_t instruction)
{
    int64_t imm26 =
        (int64_t)(instruction & 0x03FFFFFF);

    if (imm26 & 0x02000000)
        imm26 |= ~0x03FFFFFFLL;

    return from + (uintptr_t)(imm26 << 2);
}


static int encode_b(
    uintptr_t from,
    uintptr_t to,
    uint32_t *instruction)
{
    int64_t delta =
        (int64_t)to - (int64_t)from;

    if ((delta & 3) != 0)
        return 0;

    /*
     * AArch64 B immediate range: +/-128MB.
     */
    if (delta < -(1LL << 27) ||
        delta >= (1LL << 27))
        return 0;

    *instruction =
        0x14000000U |
        ((uint32_t)(delta >> 2) &
         0x03FFFFFFU);

    return 1;
}


#ifndef MAP_FIXED_NOREPLACE
#define MAP_FIXED_NOREPLACE 0x100000
#endif

static void *alloc_branch_island(
    uintptr_t branch_from)
{
    long page_size =
        sysconf(_SC_PAGESIZE);

    if (page_size <= 0)
        page_size = 4096;

    uintptr_t page =
        (uintptr_t)page_size;

    uintptr_t origin =
        branch_from & ~(page - 1);

    /*
     * AArch64 B/BL can reach approximately +/-128MB.
     *
     * Search every 64KB, preferring addresses below DraStic.
     * That's useful here because a large portion above the core is
     * occupied by DraStic's enormous data/BSS mapping.
     *
     * MAP_FIXED_NOREPLACE is critical: it either gives us exactly
     * the page requested or fails. It will not overwrite anything.
     */
    const uintptr_t step =
        0x10000;

    const uintptr_t max_distance =
        (1ULL << 27) - page;

    unsigned attempts = 0;

    for (uintptr_t distance = step;
         distance < max_distance;
         distance += step) {

        uintptr_t candidates[2];

        candidates[0] =
            (origin > distance) ?
            origin - distance : 0;

        candidates[1] =
            origin + distance;

        for (unsigned i = 0; i < 2; i++) {

            uintptr_t candidate =
                candidates[i];

            if (!candidate)
                continue;

            uint32_t test_branch;

            /*
             * Don't even attempt a mapping unless the resulting
             * address is reachable from the trampoline.
             */
            if (!encode_b(
                    branch_from,
                    candidate,
                    &test_branch))
                continue;

            attempts++;

            void *mem =
                mmap(
                    (void *)candidate,
                    (size_t)page_size,
                    PROT_READ | PROT_WRITE,
                    MAP_PRIVATE |
                    MAP_ANONYMOUS |
                    MAP_FIXED_NOREPLACE,
                    -1,
                    0);

            if (mem == MAP_FAILED)
                continue;

            /*
             * Older kernels may ignore MAP_FIXED_NOREPLACE.
             * Never accept an address other than the one requested.
             */
            if ((uintptr_t)mem != candidate) {
                munmap(mem,
                       (size_t)page_size);
                continue;
            }

            fprintf(stderr,
                    "[RA FRAME] branch island allocated "
                    "at %p after %u attempts "
                    "(delta=%lld bytes)\n",
                    mem,
                    attempts,
                    (long long)(
                        (intptr_t)candidate -
                        (intptr_t)branch_from));

            return mem;
        }
    }

    fprintf(stderr,
            "[RA FRAME] ERROR: "
            "no free executable-range page "
            "after %u attempts\n",
            attempts);

    return NULL;
}


static int install_frame_hook(void)
{
    uintptr_t site =
        g_core_base + FRAME_CALL_SITE;

    uintptr_t trampoline =
        g_core_base + FRAME_TRAMPOLINE;

    uintptr_t tramp_branch =
        g_core_base + FRAME_TRAMP_BRANCH;

    uint32_t site_insn = 0;
    uint32_t branch_insn = 0;
    uintptr_t counter_ptr = 0;

    memcpy(&site_insn,
           (void *)site,
           sizeof(site_insn));

    memcpy(&branch_insn,
           (void *)tramp_branch,
           sizeof(branch_insn));

    memcpy(&counter_ptr,
           (void *)(trampoline + 0x14),
           sizeof(counter_ptr));

    fprintf(stderr,
            "[RA FRAME] site +2c99c = %08x\n",
            site_insn);

    fprintf(stderr,
            "[RA FRAME] trampoline branch = %08x\n",
            branch_insn);

    fprintf(stderr,
            "[RA FRAME] NNDDSS counter = %p\n",
            (void *)counter_ptr);

    /*
     * NNDDSS should already have changed the original BL at +2C99C
     * into a BL to +132F00.
     */
    if ((site_insn & 0xFC000000U) !=
        0x94000000U) {
        fprintf(stderr,
                "[RA FRAME] ERROR: "
                "frame site is not BL\n");
        return 0;
    }

    uintptr_t site_target =
        decode_branch_target(
            site,
            site_insn);

    if (site_target != trampoline) {
        fprintf(stderr,
                "[RA FRAME] ERROR: "
                "site target=%p expected=%p\n",
                (void *)site_target,
                (void *)trampoline);
        return 0;
    }

    /*
     * +132F10 is NNDDSS's final B to the original DraStic
     * function. Capture that destination before replacing it.
     */
    if ((branch_insn & 0xFC000000U) !=
        0x14000000U) {
        fprintf(stderr,
                "[RA FRAME] ERROR: "
                "trampoline tail is not B\n");
        return 0;
    }

    g_original_frame_target =
        decode_branch_target(
            tramp_branch,
            branch_insn);

    fprintf(stderr,
            "[RA FRAME] original target = %p "
            "(core +0x%lx)\n",
            (void *)g_original_frame_target,
            (unsigned long)
                (g_original_frame_target -
                 g_core_base));

    void *island =
        alloc_branch_island(
            tramp_branch);

    if (!island) {
        fprintf(stderr,
                "[RA FRAME] ERROR: "
                "could not allocate near branch island\n");
        return 0;
    }

    /*
     * Island:
     *
     *   ldr x16, #8
     *   br  x16
     *   .quad ra_frame_wrapper
     */
    uint32_t island_code[2];

    island_code[0] = 0x58000050U;
    island_code[1] = 0xD61F0200U;

    memcpy(island,
           island_code,
           sizeof(island_code));

    uintptr_t wrapper =
        (uintptr_t)&ra_frame_wrapper;

    memcpy((uint8_t *)island + 8,
           &wrapper,
           sizeof(wrapper));

    __builtin___clear_cache(
        (char *)island,
        (char *)island + 16);

    long page_size =
        sysconf(_SC_PAGESIZE);

    if (page_size <= 0)
        page_size = 4096;

    if (mprotect(
            island,
            (size_t)page_size,
            PROT_READ | PROT_EXEC) != 0) {
        perror("[RA FRAME] mprotect island");
        return 0;
    }

    uint32_t new_branch;

    if (!encode_b(
            tramp_branch,
            (uintptr_t)island,
            &new_branch)) {
        fprintf(stderr,
                "[RA FRAME] ERROR: "
                "island outside branch range\n");
        return 0;
    }

    uintptr_t patch_page =
        tramp_branch &
        ~((uintptr_t)page_size - 1);

    if (mprotect(
            (void *)patch_page,
            (size_t)page_size,
            PROT_READ |
            PROT_WRITE |
            PROT_EXEC) != 0) {
        perror("[RA FRAME] mprotect core RWX");
        return 0;
    }

    /*
     * 32-bit aligned AArch64 instruction replacement.
     */
    __atomic_store_n(
        (uint32_t *)tramp_branch,
        new_branch,
        __ATOMIC_RELEASE);

    __builtin___clear_cache(
        (char *)tramp_branch,
        (char *)tramp_branch + 4);

    if (mprotect(
            (void *)patch_page,
            (size_t)page_size,
            PROT_READ | PROT_EXEC) != 0) {
        perror("[RA FRAME] mprotect core RX");
        return 0;
    }

    fprintf(stderr,
            "[RA FRAME] hook installed: "
            "%p -> island %p -> wrapper %p\n",
            (void *)tramp_branch,
            island,
            (void *)wrapper);

    return 1;
}


static void ra_7h7_first_eval_cheat_probe(void);

void ra_frame_tick(void)
{
    char rich_presence[RA_RICH_PRESENCE_MAX];
    int has_rich_presence = 0;

    rich_presence[0] = '\0';

    if (!__atomic_load_n(
            &g_ra_ready,
            __ATOMIC_ACQUIRE))
        return;

    rc_client_t *client =
        __atomic_load_n(
            &g_client,
            __ATOMIC_ACQUIRE);

    if (!client)
        return;

    pthread_mutex_lock(
        &g_ra_client_lock);

    /*
     * Re-check after taking the lock. A ROM switch may have
     * disabled RA while this frame was waiting.
     */
    if (!__atomic_load_n(
            &g_ra_ready,
            __ATOMIC_ACQUIRE) ||
        g_client != client) {

        pthread_mutex_unlock(
            &g_ra_client_lock);

        return;
    }

    /*
     * Any RA server request initiated while evaluating a frame
     * must not perform network I/O on the emulator thread.
     */
    g_ra_async_http_context = 1;

    rc_client_do_frame(client);

    g_ra_async_http_context = 0;

    /*
     * Stage 7F.2:
     * rc_client_do_frame() has just evaluated current game
     * memory. Cache Rich Presence before releasing the client
     * lock.
     */
    has_rich_presence =
        rc_client_has_rich_presence(
            client);

    if (has_rich_presence) {
        (void)rc_client_get_rich_presence_message(
            client,
            rich_presence,
            sizeof(rich_presence));

        rich_presence[
            sizeof(rich_presence) - 1] = '\0';

        snprintf(
            g_ra_rich_presence_snapshot,
            sizeof(g_ra_rich_presence_snapshot),
            "%s",
            rich_presence);

        g_ra_rich_presence_supported = 1;
    }
    else {
        g_ra_rich_presence_snapshot[0] = '\0';
        g_ra_rich_presence_supported = 0;
    }

    pthread_mutex_unlock(
        &g_ra_client_lock);

    /*
     * Stage 7F.1:
     * Log only meaningful changes. This keeps the frontend log
     * useful even for Rich Presence strings that are evaluated
     * every emulator frame.
     */
    /*
     * Stage 7F.2:
     * No per-frame Rich Presence logging. Some Rich Presence
     * scripts include clocks and legitimately change every frame.
     */

    uint64_t frame =
        __atomic_add_fetch(
            &g_ra_frame_count,
            1,
            __ATOMIC_RELAXED);

    /*
     * First few prove the hook immediately.
     * Then only log every 600 frames (~10 sec at DS speed).
     */
    if (frame <= 5 ||
        (frame % 600) == 0) {
        fprintf(stderr,
                "[RA FRAME] processed %llu\n",
                (unsigned long long)frame);
    }
}


