/* Stage 7F.2 Rich Presence snapshot bridge                                  */
/* ------------------------------------------------------------------------- */

__attribute__((visibility("default")))
int ra_rich_presence_snapshot(
    char *buffer,
    size_t buffer_size,
    int *out_supported)
{
    int supported;

    if (!buffer ||
        buffer_size == 0)
        return 0;

    buffer[0] = '\0';

    if (out_supported)
        *out_supported = 0;

    if (!__atomic_load_n(
            &g_ra_ready,
            __ATOMIC_ACQUIRE))
        return 0;

    pthread_mutex_lock(
        &g_ra_client_lock);

    if (!g_client ||
        !__atomic_load_n(
            &g_ra_ready,
            __ATOMIC_ACQUIRE)) {

        pthread_mutex_unlock(
            &g_ra_client_lock);

        return 0;
    }

    supported =
        g_ra_rich_presence_supported;

    if (out_supported)
        *out_supported = supported;

    if (supported &&
        g_ra_rich_presence_snapshot[0]) {

        snprintf(
            buffer,
            buffer_size,
            "%s",
            g_ra_rich_presence_snapshot);
    }

    pthread_mutex_unlock(
        &g_ra_client_lock);

    return 1;
}


