/* Stage 7E.1 achievement snapshot bridge                                    */
/* ------------------------------------------------------------------------- */

/*
 * The settings/UI preload must never receive raw rcheevos pointers.
 *
 * This flat snapshot structure is populated while g_ra_client_lock is held,
 * then returned entirely by value through caller-owned memory.
 */
#define RA_ACH_SNAPSHOT_TITLE_MAX       128
#define RA_ACH_SNAPSHOT_DESC_MAX        256
#define RA_ACH_SNAPSHOT_PROGRESS_MAX     24
#define RA_ACH_SNAPSHOT_BADGE_URL_MAX   512

typedef struct {
    uint32_t id;
    uint32_t points;

    float measured_percent;

    uint8_t state;
    uint8_t bucket;
    uint8_t unlocked;
    uint8_t type;

    char title[
        RA_ACH_SNAPSHOT_TITLE_MAX];

    char description[
        RA_ACH_SNAPSHOT_DESC_MAX];

    char measured_progress[
        RA_ACH_SNAPSHOT_PROGRESS_MAX];

    char badge_url[
        RA_ACH_SNAPSHOT_BADGE_URL_MAX];

    char badge_locked_url[
        RA_ACH_SNAPSHOT_BADGE_URL_MAX];
} RaAchievementSnapshotEntry;


/*
 * Copies the current game's CORE achievement set into caller-owned storage.
 *
 * No HTTP is performed here. rc_client_create_achievement_list() reads the
 * already-loaded rcheevos client state.
 *
 * out_count:
 *     number of entries actually copied to "entries"
 *
 * out_total:
 *     total number of CORE achievements, even if capacity was smaller
 *
 * Returns nonzero when a loaded achievement list was available.
 */
__attribute__((visibility("default")))
int ra_achievement_get_snapshot(
    RaAchievementSnapshotEntry *entries,
    size_t capacity,
    size_t *out_count,
    uint32_t *out_total,
    uint32_t *out_unlocked,
    uint32_t *out_total_points,
    uint32_t *out_unlocked_points)
{
    rc_client_t *client;

    rc_client_achievement_list_t *list;

    size_t copied = 0;

    uint32_t total = 0;
    uint32_t unlocked = 0;

    uint32_t total_points = 0;
    uint32_t unlocked_points = 0;

    uint32_t bucket_index;

    if (out_count)
        *out_count = 0;

    if (out_total)
        *out_total = 0;

    if (out_unlocked)
        *out_unlocked = 0;

    if (out_total_points)
        *out_total_points = 0;

    if (out_unlocked_points)
        *out_unlocked_points = 0;

    client =
        __atomic_load_n(
            &g_client,
            __ATOMIC_ACQUIRE);

    if (!client)
        return 0;

    pthread_mutex_lock(
        &g_ra_client_lock);

    /*
     * Revalidate after obtaining the client lock in case a hot-switch,
     * logout, or unload happened while we were waiting.
     */
    if (g_client != client) {
        pthread_mutex_unlock(
            &g_ra_client_lock);

        return 0;
    }

    list =
        rc_client_create_achievement_list(
            client,
            RC_CLIENT_ACHIEVEMENT_CATEGORY_CORE,
            RC_CLIENT_ACHIEVEMENT_LIST_GROUPING_LOCK_STATE);

    if (!list) {
        pthread_mutex_unlock(
            &g_ra_client_lock);

        return 0;
    }

    for (bucket_index = 0;
         bucket_index < list->num_buckets;
         ++bucket_index) {

        const rc_client_achievement_bucket_t *bucket =
            &list->buckets[bucket_index];

        uint32_t achievement_index;

        for (achievement_index = 0;
             achievement_index < bucket->num_achievements;
             ++achievement_index) {

            const rc_client_achievement_t *achievement =
                bucket->achievements[
                    achievement_index];

            int is_unlocked;

            if (!achievement)
                continue;

            ++total;

            total_points +=
                achievement->points;

            is_unlocked =
                achievement->unlocked !=
                    RC_CLIENT_ACHIEVEMENT_UNLOCKED_NONE ||
                achievement->state ==
                    RC_CLIENT_ACHIEVEMENT_STATE_UNLOCKED;

            if (is_unlocked) {
                ++unlocked;

                unlocked_points +=
                    achievement->points;
            }

            if (entries &&
                copied < capacity) {

                RaAchievementSnapshotEntry *dst =
                    &entries[copied];

                memset(
                    dst,
                    0,
                    sizeof(*dst));

                dst->id =
                    achievement->id;

                dst->points =
                    achievement->points;

                dst->measured_percent =
                    achievement->measured_percent;

                dst->state =
                    achievement->state;

                dst->bucket =
                    achievement->bucket;

                dst->unlocked =
                    achievement->unlocked;

                dst->type =
                    achievement->type;

                snprintf(
                    dst->title,
                    sizeof(dst->title),
                    "%s",
                    achievement->title ?
                        achievement->title :
                        "");

                snprintf(
                    dst->description,
                    sizeof(dst->description),
                    "%s",
                    achievement->description ?
                        achievement->description :
                        "");

                snprintf(
                    dst->measured_progress,
                    sizeof(dst->measured_progress),
                    "%s",
                    achievement->measured_progress);

                snprintf(
                    dst->badge_url,
                    sizeof(dst->badge_url),
                    "%s",
                    achievement->badge_url ?
                        achievement->badge_url :
                        "");

                snprintf(
                    dst->badge_locked_url,
                    sizeof(dst->badge_locked_url),
                    "%s",
                    achievement->badge_locked_url ?
                        achievement->badge_locked_url :
                        "");

                ++copied;
            }
        }
    }

    rc_client_destroy_achievement_list(
        list);

    pthread_mutex_unlock(
        &g_ra_client_lock);

    if (out_count)
        *out_count = copied;

    if (out_total)
        *out_total = total;

    if (out_unlocked)
        *out_unlocked = unlocked;

    if (out_total_points)
        *out_total_points = total_points;

    if (out_unlocked_points)
        *out_unlocked_points =
            unlocked_points;

    return 1;
}


