/*                                                                           */
/* Startup sequence:                                                         */
/*                                                                           */
/*   +0xB460  ldr x2,[x26,#8]     ; signalScreen                            */
/*   +0xB464  mov x0,x20          ; core                                    */
/*   +0xB468  mov x1,#0                                                   */
/*   +0xB46C  blr x2                                                      */
/*                                                                           */
