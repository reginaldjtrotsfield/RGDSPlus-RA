    g_ra_7h7j_probe_done;


static int ra_7h7j_read_cheat_state(
    void *core,
    void *drastic_fns,
    int *enabled_out)
{
    RaDrasticCheatFnsProbe *cheats;

    int count;
    int scan_count;
    int enabled_count = 0;
    int i;

    if (enabled_out)
        *enabled_out = 0;

    if (!core || !drastic_fns)
        return -1;

    cheats =
        (RaDrasticCheatFnsProbe *)
        ((uint8_t *)drastic_fns + 200);

    if (!cheats->getCheatCount ||
        !cheats->getCheatEnabled) {

        return -1;
    }

    count =
        cheats->getCheatCount(
            core,
            NULL);

    scan_count = count;

    if (scan_count < 0)
        scan_count = 0;

    if (scan_count > 65536)
        scan_count = 65536;

    for (i = 0;
         i < scan_count;
         ++i) {

        if (cheats->getCheatEnabled(
                core,
                NULL,
                i)) {

            ++enabled_count;
        }
    }

    if (enabled_out)
        *enabled_out = enabled_count;

    return count;
}



