#define NNDDSS_ROM_ACCESS_RETURN_RVA 0x7398

typedef int (*real_access_fn)(
    const char *,
    int);


int access(
    const char *path,
    int mode)
{
    static real_access_fn real_access;

    int result;

    if (!real_access) {
        real_access =
            (real_access_fn)dlsym(
                RTLD_NEXT,
                "access");

        if (!real_access) {
            errno = ENOSYS;
            return -1;
        }
    }

    result =
        real_access(
            path,
            mode);

    /*
     * NNDDSS main+0x7394:
     *
     *   mov x0, x19
     *   mov w1, #4       // R_OK
     *   bl  access@plt
     *
     * x19 is the fully resolved ROM path.
     *
     * Only capture this exact call site. Other access() calls
     * in NNDDSS and its libraries behave completely normally.
     */
    if (result == 0 &&
        path &&
        path[0] &&
        mode == R_OK) {

        void *caller =
            __builtin_return_address(0);

        Dl_info info;

        memset(
            &info,
            0,
            sizeof(info));

        if (caller &&
            dladdr(
                caller,
                &info) &&
            info.dli_fbase) {

            uintptr_t caller_rva =
                (uintptr_t)caller -
                (uintptr_t)info.dli_fbase;

            if (caller_rva ==
                NNDDSS_ROM_ACCESS_RETURN_RVA) {

                g_ra_launcher_base =
                    (uintptr_t)info.dli_fbase;

                ra_capture_runtime_rom(
                    path,
                    "startup-access");
            }
        }
    }

    return result;
}



