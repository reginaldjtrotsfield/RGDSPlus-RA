__attribute__((noinline))
static void ra_7h7j_signalscreen_wrapper(
    void *core,
    void *opaque,
    uintptr_t original_raw)
{
    ra_7h7j_signalscreen_fn original =
        (ra_7h7j_signalscreen_fn)
        (uintptr_t)original_raw;

    void *drastic_fns =
        (void *)(uintptr_t)
        g_ra_7h7j_drastic_fns;

    /*
     * IMPORTANT:
     *
     * By +0xB46C, x20 has been repurposed by the frontend.
     * Therefore signalScreen's x0 is NOT the DraStic core pointer
     * expected by the cheat API.
     *
     * Use the known-good core captured earlier at +0xAB9C.
     */
    void *cheat_core =
        (void *)(uintptr_t)
        g_ra_early_probe_core;

    int before_count;
    int before_enabled = 0;

    int after_count;
    int after_enabled = 0;


    if (!original) {
        fprintf(
            stderr,
            "[RA 7H7J] ERROR: "
            "signalScreen pointer missing\n");

        return;
    }


    if (g_ra_7h7j_probe_done) {
        original(
            core,
            opaque);

        return;
    }


    g_ra_7h7j_probe_done = 1;


    before_count =
        ra_7h7j_read_cheat_state(
            cheat_core,
            drastic_fns,
            &before_enabled);


    fprintf(
        stderr,
        "[RA 7H7L] BEFORE signalScreen "
        "signal_arg=%p cheat_core=%p drastic_fns=%p "
        "cheat_count=%d enabled=%d\n",
        core,
        cheat_core,
        drastic_fns,
        before_count,
        before_enabled);


    original(
        core,
        opaque);


    /*
     * Hold the frontend here for at most 500 ms.
     *
     * If another DraStic thread populates the cheat table without
     * any further frontend progress, getCheatCount() should change
     * from 0 to >0 while we are parked here.
     */
    {
        int poll_ms;
        int observed_count = 0;

        fprintf(
            stderr,
            "[RA 7H7L] frontend held immediately "
            "after signalScreen; polling for 500 ms\n");

        for (poll_ms = 1;
             poll_ms <= 500;
             ++poll_ms) {

            usleep(1000);

            observed_count =
                ra_7h7l_get_cheat_count_only(
                    cheat_core,
                    drastic_fns);

            if (observed_count > 0) {
                fprintf(
                    stderr,
                    "[RA 7H7L] ASYNC POPULATION OBSERVED "
                    "while frontend held: "
                    "t=%d ms cheat_count=%d\n",
                    poll_ms,
                    observed_count);

                break;
            }
        }

        if (observed_count <= 0) {
            fprintf(
                stderr,
                "[RA 7H7L] NO ASYNC POPULATION "
                "during 500 ms frontend hold; "
                "final_count=%d\n",
                observed_count);
        }
    }


    after_count =
        ra_7h7j_read_cheat_state(
            cheat_core,
            drastic_fns,
            &after_enabled);


    fprintf(
        stderr,
        "[RA 7H7L] AFTER signalScreen "
        "cheat_count=%d enabled=%d\n",
        after_count,
        after_enabled);


    if (before_count <= 0 &&
        after_count > 0) {

        fprintf(
            stderr,
            "[RA 7H7L] *** CHEAT TABLE POPULATED "
            "ACROSS signalScreen: %d -> %d ***\n",
            before_count,
            after_count);
    }
    else if (before_count > 0) {

        fprintf(
            stderr,
            "[RA 7H7L] cheat table already populated "
            "BEFORE signalScreen\n");
    }
    else {

        fprintf(
            stderr,
            "[RA 7H7L] cheat table still unavailable "
            "immediately AFTER signalScreen\n");
    }
}


static int
ra_hardcore_install_7h7j_signalscreen_probe(void)
{
    uintptr_t address;

    uint32_t found;
    uint32_t branch;

    uint8_t *island;

    long page_size =
        sysconf(_SC_PAGESIZE);


    if (g_ra_7h7j_probe_installed)
        return 1;


    if (!g_ra_launcher_base) {
        fprintf(
            stderr,
            "[RA 7H7J] REFUSED: "
            "launcher base unavailable\n");

        return 0;
    }


    address =
        g_ra_launcher_base +
        RA_7H7J_SIGNALSCREEN_CALL_RVA;


    found =
        *(volatile uint32_t *)address;


    if (found !=
        RA_7H7J_SIGNALSCREEN_EXPECTED) {

        fprintf(
            stderr,
            "[RA 7H7J] REFUSED: "
            "+0x%lx=%08x expected=%08x\n",
            (unsigned long)
                RA_7H7J_SIGNALSCREEN_CALL_RVA,
            found,
            RA_7H7J_SIGNALSCREEN_EXPECTED);

        return 0;
    }


    island =
        (uint8_t *)
        alloc_branch_island(
            address);


    if (!island) {
        fprintf(
            stderr,
            "[RA 7H7J] ERROR: "
            "could not allocate signalScreen island\n");

        return 0;
    }


    /*
     * Original:
     *
     *     blr x2
     *
     * Replacement:
     *
     *     bl island
     *
     * Island captures x26 only.
     *
     * x0/x1/x2 remain untouched, so:
     *
     *   x0 = core
     *   x1 = opaque
     *   x2 = original signalScreen pointer
     */

    *(uint32_t *)(island + 0) =
        0x58000090U;
        /* ldr x16,[pc,#16] */

    *(uint32_t *)(island + 4) =
        0xF900021AU;
        /* str x26,[x16] */

    *(uint32_t *)(island + 8) =
        0x58000090U;
        /* ldr x16,[pc,#16] */

    *(uint32_t *)(island + 12) =
        0xD61F0200U;
        /* br x16 */

    *(uint64_t *)(island + 16) =
        (uint64_t)(uintptr_t)
        &g_ra_7h7j_drastic_fns;

    *(uint64_t *)(island + 24) =
        (uint64_t)(uintptr_t)
        &ra_7h7j_signalscreen_wrapper;


    __builtin___clear_cache(
        (char *)island,
        (char *)(island + 32));


    if (page_size <= 0)
        page_size = 4096;


    if (mprotect(
            island,
            (size_t)page_size,
            PROT_READ |
            PROT_EXEC) != 0) {

        fprintf(
            stderr,
            "[RA 7H7J] ERROR: "
            "island mprotect RX failed: %s\n",
            strerror(errno));

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    if (!ra_hardcore_encode_bl(
            address,
            (uintptr_t)island,
            &branch)) {

        fprintf(
            stderr,
            "[RA 7H7J] ERROR: "
            "island outside BL range\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    if (!ra_hardcore_patch_word(
            address,
            branch)) {

        fprintf(
            stderr,
            "[RA 7H7J] ERROR: "
            "could not patch signalScreen callsite\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    g_ra_7h7j_probe_installed = 1;


    fprintf(
        stderr,
        "[RA 7H7L] signalScreen core-fixed probe installed "
        "site=+0x%lx island=%p launcher=%p\n",
        (unsigned long)
            RA_7H7J_SIGNALSCREEN_CALL_RVA,
        island,
        (void *)g_ra_launcher_base);


    return 1;
}



/* ========================================================================= */
/* Stage 7H.7N - pre-finalizer Hardcore persisted-cheat purge proof                  */
/*                                                                           */
/* PROOF BUILD. Clears persisted enabled bits only in Hardcore. Spectator remains enabled.                  */
/*                                                                           */
/* libnnddss.so startup loader path:                                         */
/*                                                                           */
/*   +0x7D21C  str w8,  [x19,#1132]   ; normal cheat count                  */
/*   +0x7D22C  str x0,  [x19,#1112]   ; normal cheat array                  */
/*   +0x7D23C  str x0,  [x19,#1120]   ; folder array                        */
/*   +0x7D24C  str w8,  [x19,#1080]   ; readiness flag B = 1               */
/*   +0x7D250  bl  0x7CD90             ; build/apply active cheat list       */
/*                                                                           */
/* Here x0 == x19 == cheat-manager pointer (state + 0x370).                  */
/*                                                                           */
/* Manager offsets:                                                          */
/*   +1080 = state +1956? no: manager-relative readiness used by loader      */
/*   +1112 = state +1992 = normal cheat-entry array                          */
/*   +1120 = state +2000 = folder array                                      */
/*   +1128 = state +2008 = folder count                                      */
/*   +1132 = state +2012 = normal cheat count                                */
/*                                                                           */
/* Each normal cheat entry is 0x28 bytes. Entry +0x20 contains a pointer     */
/* to the persisted enabled byte.                                            */
/* ========================================================================= */

#define RA_7H7M_FINALIZER_CALL_RVA \
    0x0007D250UL

#define RA_7H7M_FINALIZER_TARGET_RVA \
    0x0007CD90UL

#define RA_7H7M_FINALIZER_EXPECTED \
    0x97FFFED0U /* bl 0x7cd90 */


typedef void (*ra_7h7m_finalizer_fn)(
    void *manager);


static uintptr_t
    g_ra_7h7m_original_finalizer;

static int
    g_ra_7h7m_probe_installed;

static unsigned int
    g_ra_7h7m_call_count;


static void
ra_7h7m_inspect_manager(
    void *manager,
    const char *phase)
{
    uint8_t *m =
        (uint8_t *)manager;

    void *cheat_array;
    void *folder_array;

    uint32_t folder_count;
    uint32_t cheat_count;
    uint32_t ready_b;

    unsigned int enabled_count = 0;
    unsigned int scan_count;
    unsigned int i;


    if (!manager) {
        fprintf(
            stderr,
            "[RA 7H7S] %s manager=NULL\n",
            phase);

        return;
    }


    memcpy(
        &ready_b,
        m + 1080,
        sizeof(ready_b));

    memcpy(
        &cheat_array,
        m + 1112,
        sizeof(cheat_array));

    memcpy(
        &folder_array,
        m + 1120,
        sizeof(folder_array));

    memcpy(
        &folder_count,
        m + 1128,
        sizeof(folder_count));

    memcpy(
        &cheat_count,
        m + 1132,
        sizeof(cheat_count));


    scan_count = cheat_count;

    if (scan_count > 65536U)
        scan_count = 65536U;


    if (cheat_array) {
        uint8_t *entries =
            (uint8_t *)cheat_array;

        for (i = 0;
             i < scan_count;
             ++i) {

            uint8_t *enabled_ptr = NULL;

            memcpy(
                &enabled_ptr,
                entries +
                    ((size_t)i * 0x28U) +
                    0x20U,
                sizeof(enabled_ptr));

            if (enabled_ptr &&
                *enabled_ptr) {

                ++enabled_count;
            }
        }
    }


    fprintf(
        stderr,
        "[RA 7H7S] %s "
        "manager=%p ready_b=%u "
        "cheat_array=%p cheat_count=%u "
        "folder_array=%p folder_count=%u "
        "enabled=%u\n",
        phase,
        manager,
        ready_b,
        cheat_array,
        cheat_count,
        folder_array,
        folder_count,
        enabled_count);
}



/*
 * Stage 7H.7N
 *
 * The finalizer hook executes before the RA worker has necessarily
 * initialized rc_client, so use the same persisted settings preference
 * that the worker will use when it enables/disables Hardcore.
 */
static int ra_hardcore_startup_preference(void);


static unsigned int
ra_7h7n_count_enabled(
    void *manager)
{
    uint8_t *m =
        (uint8_t *)manager;

    void *cheat_array = NULL;
    uint32_t cheat_count = 0;

    unsigned int count = 0;
    unsigned int scan_count;
    unsigned int i;


    if (!manager)
        return 0;


    memcpy(
        &cheat_array,
        m + 1112,
        sizeof(cheat_array));

    memcpy(
        &cheat_count,
        m + 1132,
        sizeof(cheat_count));


    if (!cheat_array)
        return 0;


    scan_count = cheat_count;

    if (scan_count > 65536U)
        scan_count = 65536U;


    for (i = 0;
         i < scan_count;
         ++i) {

        uint8_t *enabled_ptr = NULL;

        memcpy(
            &enabled_ptr,
            (uint8_t *)cheat_array +
                ((size_t)i * 0x28U) +
                0x20U,
            sizeof(enabled_ptr));

        if (enabled_ptr &&
            *enabled_ptr) {

            ++count;
        }
    }


    return count;
}


static unsigned int
ra_7h7n_clear_persisted_enabled(
    void *manager)
{
    uint8_t *m =
        (uint8_t *)manager;

    void *cheat_array = NULL;
    uint32_t cheat_count = 0;

    unsigned int cleared = 0;
    unsigned int scan_count;
    unsigned int i;


    if (!manager)
        return 0;


    memcpy(
        &cheat_array,
        m + 1112,
        sizeof(cheat_array));

    memcpy(
        &cheat_count,
        m + 1132,
        sizeof(cheat_count));


    if (!cheat_array)
        return 0;


    scan_count = cheat_count;

    if (scan_count > 65536U)
        scan_count = 65536U;


    for (i = 0;
         i < scan_count;
         ++i) {

        uint8_t *enabled_ptr = NULL;

        memcpy(
            &enabled_ptr,
            (uint8_t *)cheat_array +
                ((size_t)i * 0x28U) +
                0x20U,
            sizeof(enabled_ptr));


        if (enabled_ptr &&
            *enabled_ptr) {

            fprintf(
                stderr,
                "[RA 7H7S] clearing persisted "
                "enabled cheat=%u ptr=%p\n",
                i,
                enabled_ptr);

            /*
             * This is the exact byte later read by 0x7CD90
             * and by getCheatEnabled/setCheatEnabled.
             *
             * Clear it before 0x7CD90 constructs the active list.
             */
            *enabled_ptr = 0;

            ++cleared;
        }
    }


    /*
     * Make our stores visible before entering DraStic's
     * active-cheat-list builder on this thread.
     */
    __atomic_thread_fence(
        __ATOMIC_SEQ_CST);


    return cleared;
}


__attribute__((noinline))
static void
ra_7h7m_finalizer_wrapper(
    void *manager)
{
    ra_7h7m_finalizer_fn original =
        (ra_7h7m_finalizer_fn)
        (uintptr_t)
        g_ra_7h7m_original_finalizer;

    unsigned int call_no =
        __atomic_add_fetch(
            &g_ra_7h7m_call_count,
            1U,
            __ATOMIC_RELAXED);

    unsigned int before_enabled;
    unsigned int cleared = 0;
    unsigned int remaining;

    int hardcore_requested;


    fprintf(
        stderr,
        "[RA 7H7S] FINALIZER ENTER "
        "call=%u thread=%lu\n",
        call_no,
        (unsigned long)pthread_self());


    ra_7h7m_inspect_manager(
        manager,
        "BEFORE HARDCORE PURGE");


    before_enabled =
        ra_7h7n_count_enabled(
            manager);


    /*
     * Use the exact same persisted preference that the RA worker
     * will later apply to rc_client for this process launch.
     */
    hardcore_requested =
        ra_hardcore_startup_preference();


    fprintf(
        stderr,
        "[RA 7H7S] startup Hardcore "
        "preference=%d enabled_before=%u\n",
        hardcore_requested,
        before_enabled);


    if (hardcore_requested) {

        cleared =
            ra_7h7n_clear_persisted_enabled(
                manager);


        remaining =
            ra_7h7n_count_enabled(
                manager);


        fprintf(
            stderr,
            "[RA 7H7S] PRE-FINALIZER PURGE "
            "cleared=%u remaining=%u\n",
            cleared,
            remaining);


        if (remaining != 0) {
            fprintf(
                stderr,
                "[RA 7H7S] *** PURGE FAILURE: "
                "enabled cheats remain before 7CD90 ***\n");
        }
        else {
            fprintf(
                stderr,
                "[RA 7H7S] PURGE VERIFIED "
                "before original 7CD90\n");
        }
    }
    else {

        remaining = before_enabled;

        fprintf(
            stderr,
            "[RA 7H7S] SOFTCORE: "
            "persisted cheats left untouched "
            "enabled=%u\n",
            remaining);
    }


    if (!original) {
        fprintf(
            stderr,
            "[RA 7H7S] ERROR: "
            "original 7CD90 target missing\n");

        return;
    }


    /*
     * Let DraStic build its active cheat list naturally,
     * but only after Hardcore persisted-enabled bits have
     * been cleared.
     */
    original(
        manager);


    remaining =
        ra_7h7n_count_enabled(
            manager);


    ra_7h7m_inspect_manager(
        manager,
        "AFTER ORIGINAL 7CD90");


    fprintf(
        stderr,
        "[RA 7H7S] FINALIZER EXIT "
        "call=%u enabled_after=%u\n",
        call_no,
        remaining);
}


static int
ra_hardcore_install_7h7m_finalizer_probe(void)
{
    uintptr_t address;

    uint32_t found;
    uint32_t branch;

    uint8_t *island;

    long page_size =
        sysconf(_SC_PAGESIZE);


    if (g_ra_7h7m_probe_installed)
        return 1;


    if (!g_core_base) {
        fprintf(
            stderr,
            "[RA 7H7S] REFUSED: "
            "core base unavailable\n");

        return 0;
    }


    address =
        g_core_base +
        RA_7H7M_FINALIZER_CALL_RVA;


    found =
        *(volatile uint32_t *)address;


    if (found !=
        RA_7H7M_FINALIZER_EXPECTED) {

        fprintf(
            stderr,
            "[RA 7H7S] REFUSED: "
            "core+0x%lx=%08x expected=%08x\n",
            (unsigned long)
                RA_7H7M_FINALIZER_CALL_RVA,
            found,
            RA_7H7M_FINALIZER_EXPECTED);

        return 0;
    }


    g_ra_7h7m_original_finalizer =
        g_core_base +
        RA_7H7M_FINALIZER_TARGET_RVA;


    island =
        (uint8_t *)
        alloc_branch_island(
            address);


    if (!island) {
        fprintf(
            stderr,
            "[RA 7H7S] ERROR: "
            "could not allocate finalizer island\n");

        return 0;
    }


    /*
     * Patched core instruction:
     *
     *     bl island
     *
     * Island:
     *
     *   +0   ldr x16,[pc,#8]
     *   +4   br  x16
     *   +8   .quad ra_7h7m_finalizer_wrapper
     *
     * x0 remains the original manager pointer.
     * BL creates the return address expected by our C wrapper.
     */

    *(uint32_t *)(island + 0) =
        0x58000050U;
        /* ldr x16,[pc,#8] */

    *(uint32_t *)(island + 4) =
        0xD61F0200U;
        /* br x16 */

    *(uint64_t *)(island + 8) =
        (uint64_t)(uintptr_t)
        &ra_7h7m_finalizer_wrapper;


    __builtin___clear_cache(
        (char *)island,
        (char *)(island + 16));


    if (page_size <= 0)
        page_size = 4096;


    if (mprotect(
            island,
            (size_t)page_size,
            PROT_READ |
            PROT_EXEC) != 0) {

        fprintf(
            stderr,
            "[RA 7H7S] ERROR: "
            "island mprotect RX failed: %s\n",
            strerror(errno));

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    if (!ra_hardcore_encode_bl(
            address,
            (uintptr_t)island,
            &branch)) {

        fprintf(
            stderr,
            "[RA 7H7S] ERROR: "
            "finalizer island outside BL range\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    if (!ra_hardcore_patch_word(
            address,
            branch)) {

        fprintf(
            stderr,
            "[RA 7H7S] ERROR: "
            "could not patch core finalizer call\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }


    g_ra_7h7m_probe_installed = 1;


    fprintf(
        stderr,
        "[RA 7H7S] Hardcore startup cheat guard installed "
        "core=%p site=+0x%lx island=%p "
        "original=%p\n",
        (void *)g_core_base,
        (unsigned long)
            RA_7H7M_FINALIZER_CALL_RVA,
        island,
        (void *)
            g_ra_7h7m_original_finalizer);


    return 1;
}


/*
 * Stage 7B visual-settings bridge.
 *
 * The settings preload exports this getter. We resolve it lazily
 * through RTLD_DEFAULT so achievement evaluation/submission remains
 * completely independent of the UI setting.
 */
typedef int (*ra_setting_getter_fn)(void);

static ra_setting_getter_fn
    g_ra_get_achievement_popups_enabled;

static int
    g_ra_popup_setting_resolved;


static int ra_popups_enabled(void)
{
    if (!g_ra_popup_setting_resolved) {
        g_ra_popup_setting_resolved = 1;

        g_ra_get_achievement_popups_enabled =
            (ra_setting_getter_fn)dlsym(
                RTLD_DEFAULT,
                "ra_settings_achievement_popups_enabled");
    }

    /*
     * Fail open. If the settings library is ever unavailable,
     * retain the proven Stage 6B behavior.
     */
    if (!g_ra_get_achievement_popups_enabled)
        return 1;

    return
        g_ra_get_achievement_popups_enabled() ?
        1 :
        0;
}


static void ra_event_handler(
    const rc_client_event_t *event,
    rc_client_t *client)
{
    (void)client;

    switch (event->type) {

    case RC_CLIENT_EVENT_ACHIEVEMENT_TRIGGERED:
        if (event->achievement) {
            fprintf(stderr,
                    "[RA EVENT] ACHIEVEMENT: "
                    "%u \"%s\" (%u points)\n",
                    event->achievement->id,
                    event->achievement->title,
                    event->achievement->points);

            if (ra_popups_enabled()) {
                ra_queue_achievement_popup_badged(
                    event->achievement->title,
                    event->achievement->points,
                    event->achievement->badge_url);
            }
            else {
                fprintf(
                    stderr,
                    "[RA EVENT] achievement popup suppressed by setting\n");
            }
        }
        break;

    case RC_CLIENT_EVENT_ACHIEVEMENT_CHALLENGE_INDICATOR_SHOW:
        if (event->achievement) {
            fprintf(stderr,
                    "[RA EVENT] CHALLENGE SHOW: %u \"%s\"\n",
                    event->achievement->id,
                    event->achievement->title ?
                        event->achievement->title : "?");

            ra_bridge_challenge_show(
                event->achievement->id,
                event->achievement->title,
                event->achievement->badge_url);
        }
        break;

    case RC_CLIENT_EVENT_ACHIEVEMENT_CHALLENGE_INDICATOR_HIDE:
        if (event->achievement) {
            fprintf(stderr,
                    "[RA EVENT] CHALLENGE HIDE: %u \"%s\"\n",
                    event->achievement->id,
                    event->achievement->title ?
                        event->achievement->title : "?");

            ra_bridge_challenge_hide(
                event->achievement->id);
        }
        else {
            fprintf(stderr,
                    "[RA EVENT] CHALLENGE HIDE\n");

            ra_bridge_challenge_hide(0);
        }
        break;

    case RC_CLIENT_EVENT_ACHIEVEMENT_PROGRESS_INDICATOR_SHOW:
        if (event->achievement) {
            fprintf(stderr,
                    "[RA EVENT] PROGRESS SHOW: "
                    "%u \"%s\" %s %.1f%%\n",
                    event->achievement->id,
                    event->achievement->title ?
                        event->achievement->title : "?",
                    event->achievement->measured_progress,
                    event->achievement->measured_percent);

            ra_bridge_progress_update(
                event->achievement->id,
                event->achievement->title,
                event->achievement->measured_progress,
                event->achievement->measured_percent);
        }
        break;

    case RC_CLIENT_EVENT_ACHIEVEMENT_PROGRESS_INDICATOR_UPDATE:
        if (event->achievement) {
            fprintf(stderr,
                    "[RA EVENT] PROGRESS UPDATE: "
                    "%u \"%s\" %s %.1f%%\n",
                    event->achievement->id,
                    event->achievement->title ?
                        event->achievement->title : "?",
                    event->achievement->measured_progress,
                    event->achievement->measured_percent);

            ra_bridge_progress_update(
                event->achievement->id,
                event->achievement->title,
                event->achievement->measured_progress,
                event->achievement->measured_percent);
        }
        break;

    case RC_CLIENT_EVENT_ACHIEVEMENT_PROGRESS_INDICATOR_HIDE:
        fprintf(stderr,
                "[RA EVENT] PROGRESS HIDE\n");

        ra_bridge_progress_hide();
        break;

    case RC_CLIENT_EVENT_LEADERBOARD_STARTED:
        if (event->leaderboard) {
            fprintf(stderr,
                    "[RA EVENT] LEADERBOARD START: %s\n",
                    event->leaderboard->title);
        }
        break;

    case RC_CLIENT_EVENT_LEADERBOARD_FAILED:
        if (event->leaderboard) {
            fprintf(stderr,
                    "[RA EVENT] LEADERBOARD FAILED: %s\n",
                    event->leaderboard->title);
        }
        break;

    case RC_CLIENT_EVENT_LEADERBOARD_SUBMITTED:
        if (event->leaderboard) {
            fprintf(stderr,
                    "[RA EVENT] LEADERBOARD SUBMITTED: %s\n",
                    event->leaderboard->title);
        }
        break;

    case RC_CLIENT_EVENT_RESET:
        fprintf(
            stderr,
            "[RA 7H3] RESET EVENT RECEIVED - "
            "unexpected during startup proof\n");
        break;

    case RC_CLIENT_EVENT_GAME_COMPLETED:
        fprintf(stderr,
                "[RA EVENT] GAME COMPLETED\n");
        break;

    case RC_CLIENT_EVENT_SERVER_ERROR:
        if (event->server_error) {
            fprintf(stderr,
                    "[RA EVENT] SERVER ERROR: %s: %s\n",
                    event->server_error->api ?
                        event->server_error->api : "?",
                    event->server_error->error_message ?
                        event->server_error->error_message : "?");
        }
        break;

    case RC_CLIENT_EVENT_DISCONNECTED:
        fprintf(stderr,
                "[RA EVENT] SERVER DISCONNECTED\n");
        break;

    case RC_CLIENT_EVENT_RECONNECTED:
        fprintf(stderr,
                "[RA EVENT] SERVER RECONNECTED\n");
        break;

    default:
        break;
    }
}


static void ra_log(
    const char *message,
    const rc_client_t *client)
{
    (void)client;
    fprintf(stderr, "[rcheevos] %s\n", message);
}


static volatile int g_login_done;
static volatile int g_login_result = -1;

static volatile int g_game_done;
static volatile int g_game_result = -1;


/*
 * Stage 7D.6:
 * Wait for an asynchronous startup/hot-switch operation.
 *
 * After the callback signals completion, take g_ra_client_lock once
 * to guarantee the HTTP completion thread has fully finished touching
 * the rcheevos client before this thread continues.
 */
static int ra_wait_global_done(
    volatile int *done,
    unsigned timeout_ms,
    const char *what)
{
    unsigned waited = 0;

    while (!__atomic_load_n(
               done,
               __ATOMIC_ACQUIRE)) {

        if (waited >= timeout_ms) {
            fprintf(
                stderr,
                "[RA WAIT] timeout: %s\n",
                what ? what : "?");

            return 0;
        }

        usleep(10000);
        waited += 10;
    }

    pthread_mutex_lock(
        &g_ra_client_lock);

    pthread_mutex_unlock(
        &g_ra_client_lock);

    fprintf(
        stderr,
        "[RA WAIT] completed: %s (%u ms max)\n",
        what ? what : "?",
        waited);

    return 1;
}


static void login_callback(
    int result,
    const char *error_message,
    rc_client_t *client,
    void *userdata)
{
    (void)client;
    (void)userdata;

    g_login_result = result;

    __atomic_store_n(
        &g_login_done,
        1,
        __ATOMIC_RELEASE);

    if (result == RC_OK)
        fprintf(stderr, "[RA] LOGIN SUCCESS\n");
    else
        fprintf(stderr,
                "[RA] LOGIN FAILED: %s (%d)\n",
                error_message ?
                    error_message :
                    rc_error_str(result),
                result);
}


static void game_callback(
    int result,
    const char *error_message,
    rc_client_t *client,
    void *userdata)
{
    (void)client;
    (void)userdata;

    g_game_result = result;

    __atomic_store_n(
        &g_game_done,
        1,
        __ATOMIC_RELEASE);

    if (result == RC_OK) {
        fprintf(stderr, "[RA] GAME LOAD SUCCESS\n");

        /*
         * Verify the optional popup renderer is present now,
         * rather than discovering a missing symbol during an unlock.
         */
        ra_get_popup_enqueue();
    }
    else
        fprintf(stderr,
                "[RA] GAME LOAD FAILED: %s (%d)\n",
                error_message ?
                    error_message :
                    rc_error_str(result),
                result);
}



static int ra_reload_current_game(void)
{
    char auto_hash[33];

    const char *hash =
        getenv("RA_HASH");

    if (!hash || !*hash) {
        if (!ra_generate_game_hash(
                auto_hash)) {

            fprintf(
                stderr,
                "[RA HOTSWITCH] automatic game "
                "identification failed\n");

            return 0;
        }

        hash = auto_hash;
    }

    fprintf(
        stderr,
        "[RA HOTSWITCH] loading game hash %s\n",
        hash);

    __atomic_store_n(
        &g_game_done,
        0,
        __ATOMIC_RELEASE);
    g_game_result = -1;

    pthread_mutex_lock(
        &g_ra_client_lock);

    rc_client_begin_load_game(
        g_client,
        hash,
        game_callback,
        NULL);

    pthread_mutex_unlock(
        &g_ra_client_lock);

    if (!ra_wait_global_done(
            &g_game_done,
            20000,
            "hot-switch game load")) {

        fprintf(
            stderr,
            "[RA HOTSWITCH] game load timed out\n");

        return 0;
    }

    if (!__atomic_load_n(
            &g_game_done,
            __ATOMIC_ACQUIRE) ||
        g_game_result != RC_OK) {

        if (g_game_done &&
            g_game_result ==
                RC_NO_GAME_LOADED) {

            ra_queue_unsupported_game_status();

            fprintf(
                stderr,
                "[RA HOTSWITCH] unsupported game\n");
        }

        fprintf(
            stderr,
            "[RA HOTSWITCH] game load unsuccessful\n");

        return 0;
    }

    {
        const rc_client_game_t *game =
            rc_client_get_game_info(
                g_client);

        rc_client_user_game_summary_t summary;

        if (game) {
            fprintf(
                stderr,
                "[RA HOTSWITCH] LIVE GAME: "
                "%u \"%s\"\n",
                game->id,
                game->title ?
                    game->title :
                    "?");
        }

        memset(
            &summary,
            0,
            sizeof(summary));

        rc_client_get_user_game_summary(
            g_client,
            &summary);

        fprintf(
            stderr,
            "[RA HOTSWITCH] achievements: "
            "core=%u unlocked=%u points=%u\n",
            summary.num_core_achievements,
            summary.num_unlocked_achievements,
            summary.points_core);
    }

    /*
     * Stage 7D.1:
     * show one status banner for this newly-loaded ROM generation.
     */
    ra_queue_current_game_status();

    return 1;
}


/* ------------------------------------------------------------------------- */
/* RA worker                                                                 */
/* ------------------------------------------------------------------------- */

static void *ra_worker(void *unused)
{
    const uint32_t first_page =
        MAIN_RAM_ADDR >> 11;

    const char *username;
    const char *token;
    const char *password;
    const char *hash;

    int start_signed_out;

    (void)unused;

    fprintf(stderr,
            "[RA] worker started; core=%p\n",
            (void *)g_core_base);

    /*
     * Wait for DraStic to create its emulated memory.
     */
    for (;;) {
        uintptr_t state = 0;
        uint64_t entry = 0;

        if (!safe_read(
                (void *)(g_core_base + STATE_SLOT),
                &state,
                sizeof(state)) ||
            !state) {
            usleep(100000);
            continue;
        }

        uintptr_t arm9_map =
            state + ARM9_MAP_OFF;

        if (!safe_read(
                (void *)(arm9_map +
                    ((uintptr_t)first_page * 8)),
                &entry,
                sizeof(entry)) ||
            !entry) {
            usleep(100000);
            continue;
        }

        uintptr_t bias =
            (uintptr_t)(entry << 2);

        g_main_ram =
            bias + MAIN_RAM_ADDR;

        g_dtcm =
            g_main_ram + DTCM_BACKING_OFF;

        fprintf(stderr,
                "[RA] state    = %p\n",
                (void *)state);

        fprintf(stderr,
                "[RA] ARM9 map = %p\n",
                (void *)arm9_map);

        fprintf(stderr,
                "[RA] Main RAM = %p\n",
                (void *)g_main_ram);

        fprintf(stderr,
                "[RA] DTCM     = %p\n",
                (void *)g_dtcm);

        break;
    }

    /*
     * Let game startup settle before asking rcheevos to validate
     * all achievement addresses.
     */
    usleep(1000000);

    fprintf(
        stderr,
        "[RA HOTSWITCH] V5 zero-patch "
        "fprintf ROM capture active\n");

    username = getenv("RA_USER");
    token = getenv("RA_TOKEN");
    password = getenv("RA_PASS");

    char auto_hash[33];

    hash = getenv("RA_HASH");

    if (!hash || !*hash) {
        if (!ra_generate_game_hash(auto_hash)) {
            fprintf(stderr,
                    "[RA HASH] automatic game "
                    "identification failed\n");
            return NULL;
        }

        hash = auto_hash;
    }

    if (!username || !*username) {
        fprintf(stderr,
                "[RA] RA_USER is not set - RA disabled\n");
        return NULL;
    }

    start_signed_out =
        ((!token || !*token) &&
         (!password || !*password));

    if (start_signed_out) {
        fprintf(
            stderr,
            "[RA ACCOUNT] no saved credentials - "
            "starting signed out\n");
    }

    if (!init_curl())
        return NULL;

    g_client =
        rc_client_create(
            ra_read_memory,
            ra_server_call);

    if (!g_client) {
        fprintf(stderr,
                "[RA] rc_client_create failed\n");
        return NULL;
    }

    rc_client_enable_logging(
        g_client,
        RC_CLIENT_LOG_LEVEL_VERBOSE,
        ra_log);

    rc_client_set_event_handler(
        g_client,
        ra_event_handler);

    /*
     * Stage 2 validation runs in spectator mode:
     * evaluate normally, but do not submit unlocks/leaderboards.
     */
    /*
     * Stage 7H.3:
     *
     * Hardcore startup proof.
     *
     * Keep spectator mode enabled until the frontend's Hardcore
     * restrictions are complete. This allows us to validate the
     * rcheevos mode without submitting Hardcore unlocks or
     * leaderboard scores from a non-compliant frontend.
     */
    rc_client_set_spectator_mode_enabled(
        g_client,
        1);

    /*
     * Stage 7H.6:
     *
     * Consume the persisted Hardcore preference BEFORE any game is
     * loaded. This avoids the runtime RESET handshake required when
     * enabling Hardcore with an already-active rcheevos game.
     */
    {
        int requested_hardcore =
            ra_hardcore_startup_preference();

        rc_client_set_hardcore_enabled(
            g_client,
            requested_hardcore);

        fprintf(
            stderr,
            "[RA 7H6] startup preference=%d "
            "actual_hardcore=%d spectator=%d\n",
            requested_hardcore,
            rc_client_get_hardcore_enabled(
                g_client) ? 1 : 0,
            rc_client_get_spectator_mode_enabled(
                g_client) ? 1 : 0);
    }

    fprintf(
        stderr,
        "[RA 7H7S] spectator mode enabled; "
        "achievement submissions are blocked during identity research\n");


    /*
     * Stage 7H.4:
     * Protect every known NNDDSS loadState execution path.
     *
     * Install regardless of current mode. The guard itself queries
     * the real rcheevos Hardcore state on every load request.
     */
    if (!ra_hardcore_install_load_guard()) {
        fprintf(
            stderr,
            "[RA 7H4] WARNING: "
            "load-state guard installation failed\n");
    }


    /*
     * Stage 7H.5:
     * Guard DraStic setCheatEnabled while Hardcore is active.
     */
    if (!ra_hardcore_install_cheat_guard()) {
        fprintf(
            stderr,
            "[RA 7H5] WARNING: "
            "cheat guard installation failed\n");
    }

    fprintf(stderr,
            "[RA] live memory callback enabled\n");

    /*
     * Stage 7C.3:
     *
     * Signed out is a valid persistent RA state. Keep the client
     * and DraStic frame hook alive, but leave achievement
     * evaluation disabled until interactive Sign In succeeds.
     */
    if (start_signed_out) {
        if (!install_frame_hook()) {
            fprintf(
                stderr,
                "[RA ACCOUNT] signed-out startup failed: "
                "frame hook was not installed\n");

            return NULL;
        }

        __atomic_store_n(
            &g_ra_frame_count,
            0,
            __ATOMIC_RELEASE);

        __atomic_store_n(
            &g_ra_ready,
            0,
            __ATOMIC_RELEASE);

        fprintf(
            stderr,
            "[RA ACCOUNT] SIGNED OUT READY - "
            "client alive, frame hook active, "
            "evaluation paused\n");

        goto ra_persistent_lifecycle;
    }

    __atomic_store_n(
        &g_login_done,
        0,
        __ATOMIC_RELEASE);
    g_login_result = -1;

    if (token && *token) {
        fprintf(stderr,
                "[RA] logging in as %s with token\n",
                username);

        rc_client_begin_login_with_token(
            g_client,
            username,
            token,
            login_callback,
            NULL);
    }
    else {
        fprintf(stderr,
                "[RA] logging in as %s\n",
                username);

        ra_begin_login(
            g_client,
            username,
            password,
            login_callback,
            NULL);
    }

    if (!ra_wait_global_done(
            &g_login_done,
            20000,
            "startup login")) {

        fprintf(
            stderr,
            "[RA] login timed out\n");

        return NULL;
    }

    if (!__atomic_load_n(
            &g_login_done,
            __ATOMIC_ACQUIRE) ||
        g_login_result != RC_OK) {

        fprintf(stderr,
                "[RA] login unsuccessful\n");

        return NULL;
    }

    fprintf(stderr,
            "[RA] loading game hash %s\n",
            hash);

    __atomic_store_n(
        &g_game_done,
        0,
        __ATOMIC_RELEASE);
    g_game_result = -1;

    rc_client_begin_load_game(
        g_client,
        hash,
        game_callback,
        NULL);

    if (!ra_wait_global_done(
            &g_game_done,
            20000,
            "startup game load")) {

        fprintf(
            stderr,
            "[RA] game load timed out\n");

        return NULL;
    }

    if (!__atomic_load_n(
            &g_game_done,
            __ATOMIC_ACQUIRE) ||
        g_game_result != RC_OK) {

        if (g_game_done &&
            g_game_result ==
                RC_NO_GAME_LOADED) {

            ra_queue_unsupported_game_status();

            /*
             * Keep the hot-switch lifecycle alive, but leave
             * achievement evaluation disabled for the unknown game.
             */
            if (!install_frame_hook()) {
                fprintf(
                    stderr,
                    "[RA] STAGE 2 FAILED: "
                    "frame hook was not installed\n");

                return NULL;
            }

            __atomic_store_n(
                &g_ra_frame_count,
                0,
                __ATOMIC_RELEASE);

            __atomic_store_n(
                &g_ra_ready,
                0,
                __ATOMIC_RELEASE);

            fprintf(
                stderr,
                "[RA STARTUP] unsupported game - "
                "evaluation paused; lifecycle active\n");

            goto ra_persistent_lifecycle;
        }

        fprintf(
            stderr,
            "[RA] game load unsuccessful\n");

        return NULL;
    }

    {
        const rc_client_game_t *game =
            rc_client_get_game_info(g_client);

        rc_client_user_game_summary_t summary;

        if (game) {
            fprintf(stderr,
                    "[RA] LIVE GAME: %u \"%s\"\n",
                    game->id,
                    game->title ?
                        game->title : "?");
        }

        memset(&summary, 0, sizeof(summary));

        rc_client_get_user_game_summary(
            g_client,
            &summary);

        fprintf(stderr,
                "[RA] achievements: core=%u unlocked=%u points=%u\n",
                summary.num_core_achievements,
                summary.num_unlocked_achievements,
                summary.points_core);
    }

    /*
     * Stage 7D.1:
     * normal authenticated startup status notification.
     */
    ra_queue_current_game_status();

    if (!install_frame_hook()) {
        fprintf(stderr,
                "[RA] STAGE 2 FAILED: "
                "frame hook was not installed\n");
        return NULL;
    }

    __atomic_store_n(
        &g_ra_frame_count,
        0,
        __ATOMIC_RELEASE);

    __atomic_store_n(
        &g_ra_ready,
        1,
        __ATOMIC_RELEASE);

    {
        int hardcore_enabled;
        int spectator_enabled;

        pthread_mutex_lock(
            &g_ra_client_lock);

        hardcore_enabled =
            rc_client_get_hardcore_enabled(
                g_client) ?
                1 :
                0;

        spectator_enabled =
            rc_client_get_spectator_mode_enabled(
                g_client) ?
                1 :
                0;

        pthread_mutex_unlock(
            &g_ra_client_lock);

        fprintf(
            stderr,
            "[RA 7H3] post-load mode: "
            "hardcore=%d spectator=%d\n",
            hardcore_enabled,
            spectator_enabled);
    }

    fprintf(
        stderr,
        "[RA] STAGE 2B READY - "
        "FRAME PROCESSING ACTIVE "
        "(HARDCORE PROOF / SPECTATOR)\n");

ra_persistent_lifecycle:
    ;

    /*
     * Stage 7B.5:
     *
     * The worker now remains responsible for the lifetime of the
     * emulator process instead of going permanently idle after the
     * first game.
     */
    uint64_t handled_rom_generation =
        __atomic_load_n(
            &g_ra_rom_generation,
            __ATOMIC_ACQUIRE);

    uint64_t hooked_core_generation =
        __atomic_load_n(
            &g_ra_core_generation,
            __ATOMIC_ACQUIRE);

    for (;;) {
        uint64_t current_core_generation =
            __atomic_load_n(
                &g_ra_core_generation,
                __ATOMIC_ACQUIRE);

        /*
         * A new DraStic shared object was loaded.
         *
         * NNDDSS installs its frame-split trampoline after dlmopen,
         * so wait until that native patch is present before applying
         * our tail hook again.
         */
        if (current_core_generation !=
            hooked_core_generation) {

            unsigned attempt;
            int installed = 0;

            __atomic_store_n(
                &g_ra_ready,
                0,
                __ATOMIC_RELEASE);

            fprintf(
                stderr,
                "[RA HOTSWITCH] core generation "
                "%llu -> %llu\n",
                (unsigned long long)
                    hooked_core_generation,
                (unsigned long long)
                    current_core_generation);

            /*
             * Give NNDDSS a moment to finish dyn_load(), symbol
             * resolution and nnddss_frame_split_install().
             */
            usleep(500000);

            for (attempt = 0;
                 attempt < 50;
                 ++attempt) {

                /*
                 * If another core arrives, restart on the next
                 * lifecycle iteration using the newest generation.
                 */
                if (__atomic_load_n(
                        &g_ra_core_generation,
                        __ATOMIC_ACQUIRE) !=
                    current_core_generation) {

                    break;
                }

                if (install_frame_hook()) {
                    installed = 1;
                    break;
                }

                usleep(100000);
            }

            if (!installed) {
                fprintf(
                    stderr,
                    "[RA HOTSWITCH] waiting for "
                    "new core frame hook\n");

                usleep(250000);
                continue;
            }

            if (!ra_refresh_memory_map()) {
                usleep(250000);
                continue;
            }

            hooked_core_generation =
                current_core_generation;

            /*
             * If the ROM itself did not change, the already-loaded
             * RA game can continue against the refreshed memory.
             *
             * Normally a ROM generation follows immediately and
             * the game reload branch below handles it.
             */
            if (__atomic_load_n(
                    &g_ra_rom_generation,
                    __ATOMIC_ACQUIRE) ==
                    handled_rom_generation &&
                g_client &&
                rc_client_get_game_info(g_client)) {

                __atomic_store_n(
                    &g_ra_ready,
                    1,
                    __ATOMIC_RELEASE);
            }

            continue;
        }


        uint64_t current_rom_generation =
            __atomic_load_n(
                &g_ra_rom_generation,
                __ATOMIC_ACQUIRE);

        if (current_rom_generation !=
            handled_rom_generation) {

            uint64_t target_generation =
                current_rom_generation;

            fprintf(
                stderr,
                "[RA HOTSWITCH] processing ROM "
                "generation %llu\n",
                (unsigned long long)
                    target_generation);

            __atomic_store_n(
                &g_ra_ready,
                0,
                __ATOMIC_RELEASE);

            /*
             * Remove visual state from the old game immediately.
             */
            ra_bridge_clear_game_state();

            /*
             * Stop evaluating the old achievement set before
             * touching the new game's memory.
             */
            pthread_mutex_lock(
                &g_ra_client_lock);

            if (g_client)
                rc_client_unload_game(
                    g_client);

            pthread_mutex_unlock(
                &g_ra_client_lock);

            g_main_ram = 0;
            g_dtcm = 0;

            /*
             * The ROM-path access check occurs shortly before
             * NNDDSS performs the actual game launch. Let that
             * transition finish.
             */
            usleep(1000000);

            /*
             * Another ROM was selected while we were waiting.
             * Skip this stale generation and process the newest one.
             */
            if (__atomic_load_n(
                    &g_ra_rom_generation,
                    __ATOMIC_ACQUIRE) !=
                target_generation) {

                continue;
            }

            /*
             * If a new core arrived, service that first so the frame
             * hook and memory callbacks point at the correct image.
             */
            if (__atomic_load_n(
                    &g_ra_core_generation,
                    __ATOMIC_ACQUIRE) !=
                hooked_core_generation) {

                continue;
            }

            if (!ra_refresh_memory_map()) {
                fprintf(
                    stderr,
                    "[RA HOTSWITCH] new memory map "
                    "not ready; retrying\n");

                usleep(250000);
                continue;
            }

            /*
             * Let the new title finish its initial boot before
             * rcheevos validates/evaluates its address set.
             */
            usleep(500000);

            /*
             * Stage 7C.3:
             *
             * ROM switching remains fully tracked while signed out.
             * Defer the rcheevos game load until the user signs in.
             */
            if (!ra_account_is_logged_in()) {
                handled_rom_generation =
                    target_generation;

                fprintf(
                    stderr,
                    "[RA HOTSWITCH] generation %llu ready "
                    "while signed out - RA game load deferred\n",
                    (unsigned long long)
                        target_generation);

                continue;
            }

            if (!ra_reload_current_game()) {
                /*
                 * Mark this generation handled so we fail safe:
                 * RA remains inactive instead of repeatedly loading
                 * or evaluating the old game's achievement set.
                 */
                handled_rom_generation =
                    target_generation;

                fprintf(
                    stderr,
                    "[RA HOTSWITCH] RA inactive for "
                    "this ROM\n");

                continue;
            }

            /*
             * Guard against a third game being selected during the
             * network/load operation.
             */
            if (__atomic_load_n(
                    &g_ra_rom_generation,
                    __ATOMIC_ACQUIRE) !=
                target_generation) {

                pthread_mutex_lock(
                    &g_ra_client_lock);

                rc_client_unload_game(
                    g_client);

                pthread_mutex_unlock(
                    &g_ra_client_lock);

                continue;
            }

            handled_rom_generation =
                target_generation;

            __atomic_store_n(
                &g_ra_frame_count,
                0,
                __ATOMIC_RELEASE);

            __atomic_store_n(
                &g_ra_ready,
                1,
                __ATOMIC_RELEASE);

            fprintf(
                stderr,
                "[RA HOTSWITCH] READY generation=%llu\n",
                (unsigned long long)
                    target_generation);
        }

        usleep(100000);
    }

    return NULL;
}


/* ------------------------------------------------------------------------- */
/* Intercept the launcher's dlmopen of libnnddss.so                          */
/* ------------------------------------------------------------------------- */

void *dlmopen(
    Lmid_t nsid,
    const char *filename,
    int flags)
{
    static dlmopen_fn real_dlmopen;

    if (!real_dlmopen) {
        real_dlmopen =
            (dlmopen_fn)dlsym(
                RTLD_NEXT,
                "dlmopen");

        if (!real_dlmopen) {
            fprintf(stderr,
                    "[RA] cannot resolve real dlmopen\n");
            return NULL;
        }
    }

    void *handle =
        real_dlmopen(nsid, filename, flags);

    if (handle &&
        filename &&
        strstr(filename, "libnnddss.so") &&
        !strstr(filename, "renegade")) {

        struct link_map *lm = NULL;

        if (dlinfo(handle,
                   RTLD_DI_LINKMAP,
                   &lm) == 0 &&
            lm) {

            g_core_base =
                (uintptr_t)lm->l_addr;

            uint64_t core_generation =
                __atomic_add_fetch(
                    &g_ra_core_generation,
                    1,
                    __ATOMIC_RELEASE);

            /*
             * A newly mapped core cannot use the frame hook from the
             * previous mapping.
             */
            __atomic_store_n(
                &g_ra_ready,
                0,
                __ATOMIC_RELEASE);

            fprintf(
                stderr,
                "[RA HOTSWITCH] core loaded generation=%llu\n",
                (unsigned long long)core_generation);

            fprintf(stderr,
                    "[RA] DraStic core loaded: "
                    "%s base=%p\n",
                    filename,
                    (void *)g_core_base);

            /*
             * Stage 7H.7T:
             *
             * Protect every known launcher loadState path synchronously
             * before dlmopen returns. This closes the startup/auto-resume
             * window that existed before the RA worker initialized.
             */
            if (!ra_hardcore_install_load_guard()) {
                fprintf(
                    stderr,
                    "[RA 7H7T] WARNING: "
                    "early load-state guard installation failed\n");
            }
            else {
                fprintf(
                    stderr,
                    "[RA 7H7T] EARLY load-state guard ready "
                    "before dlmopen return\n");
            }

            /*
             * Patch libnnddss.so's normal-cheat loader finalizer
             * synchronously before dlmopen returns.
             */
            if (!ra_hardcore_install_7h7m_finalizer_probe()) {
                fprintf(
                    stderr,
                    "[RA 7H7S] WARNING: "
                    "Hardcore startup cheat guard installation failed\n");
            }

            if (!g_worker_started) {
                pthread_t thread;

                g_worker_started = 1;

                if (pthread_create(
                        &thread,
                        NULL,
                        ra_worker,
                        NULL) == 0) {

                    pthread_detach(thread);
                }
                else {
                    fprintf(stderr,
                            "[RA] pthread_create failed\n");
                }
            }
        }
    }

    return handle;
}


