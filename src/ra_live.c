static int safe_read(const void *src, void *dst, size_t size)
{
    struct iovec local = {
        .iov_base = dst,
        .iov_len = size
    };

    struct iovec remote = {
        .iov_base = (void *)src,
        .iov_len = size
    };

    return process_vm_readv(
        getpid(),
        &local, 1,
        &remote, 1,
        0
    ) == (ssize_t)size;
}




static int ra_refresh_memory_map(void)
{
    const uint32_t first_page =
        MAIN_RAM_ADDR >> 11;

    unsigned attempt;

    for (attempt = 0;
         attempt < 100;
         ++attempt) {

        uintptr_t core_base =
            __atomic_load_n(
                &g_core_base,
                __ATOMIC_ACQUIRE);

        uintptr_t state = 0;
        uint64_t entry = 0;

        if (!core_base) {
            usleep(100000);
            continue;
        }

        if (!safe_read(
                (void *)(core_base + STATE_SLOT),
                &state,
                sizeof(state)) ||
            !state) {

            usleep(100000);
            continue;
        }

        uintptr_t arm9_map =
            state + ARM9_MAP_OFF;

        if (!safe_read(
                (void *)(arm9_map +
                    ((uintptr_t)first_page * 8)),
                &entry,
                sizeof(entry)) ||
            !entry) {

            usleep(100000);
            continue;
        }

        uintptr_t bias =
            (uintptr_t)(entry << 2);

        g_main_ram =
            bias + MAIN_RAM_ADDR;

        g_dtcm =
            g_main_ram +
            DTCM_BACKING_OFF;

        fprintf(
            stderr,
            "[RA HOTSWITCH] memory refreshed "
            "state=%p RAM=%p DTCM=%p\n",
            (void *)state,
            (void *)g_main_ram,
            (void *)g_dtcm);

        return 1;
    }

    fprintf(
        stderr,
        "[RA HOTSWITCH] ERROR: "
        "timed out waiting for DS memory map\n");

    return 0;
}



