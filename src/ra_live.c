struct http_buffer {
    char *data;
    size_t size;
};


static size_t http_write(
    char *ptr,
    size_t size,
    size_t nmemb,
    void *userdata)
{
    struct http_buffer *buffer = userdata;
    size_t bytes = size * nmemb;

    char *new_data =
        realloc(buffer->data,
                buffer->size + bytes + 1);

    if (!new_data)
        return 0;

    buffer->data = new_data;

    memcpy(buffer->data + buffer->size,
           ptr,
           bytes);

    buffer->size += bytes;
    buffer->data[buffer->size] = '\0';

    return bytes;
}


typedef struct RaHttpJob {
    char *url;
    char *post_data;
    char *content_type;

    char user_agent[256];

    rc_client_server_callback_t callback;
    void *callback_data;
} RaHttpJob;


static void ra_http_job_free(
    RaHttpJob *job)
{
    if (!job)
        return;

    free(job->url);
    free(job->post_data);
    free(job->content_type);
    free(job);
}


static void ra_http_deliver(
    RaHttpJob *job,
    const rc_api_server_response_t *response,
    int serialize_client)
{
    int previous_async_context;

    if (!job ||
        !job->callback)
        return;

    if (!serialize_client) {
        job->callback(
            response,
            job->callback_data);

        return;
    }

    /*
     * rcheevos client state is also touched by ra_frame_tick().
     * Serialize the asynchronous completion against that path.
     */
    pthread_mutex_lock(
        &g_ra_client_lock);

    /*
     * If processing this response generates another server request,
     * that request must remain asynchronous too.
     */
    previous_async_context =
        g_ra_async_http_context;

    g_ra_async_http_context = 1;

    job->callback(
        response,
        job->callback_data);

    g_ra_async_http_context =
        previous_async_context;

    pthread_mutex_unlock(
        &g_ra_client_lock);
}


static void ra_http_execute(
    RaHttpJob *job,
    int serialize_client)
{
    CURL *easy;
    CURLcode result = -1;
    long http_status = 0;

    struct http_buffer response = {0};
    struct curl_slist *headers = NULL;

    easy = p_curl_easy_init();

    if (!easy) {
        rc_api_server_response_t r = {0};

        r.http_status_code =
            RC_API_SERVER_RESPONSE_CLIENT_ERROR;

        ra_http_deliver(
            job,
            &r,
            serialize_client);

        return;
    }

    p_curl_easy_setopt(
        easy,
        CURLOPT_URL,
        job->url);

    p_curl_easy_setopt(
        easy,
        CURLOPT_USERAGENT,
        job->user_agent);

    p_curl_easy_setopt(
        easy,
        CURLOPT_CAINFO,
        "/etc/ssl/certs/ca-certificates.crt");

    p_curl_easy_setopt(
        easy,
        CURLOPT_SSL_VERIFYPEER,
        1L);

    p_curl_easy_setopt(
        easy,
        CURLOPT_SSL_VERIFYHOST,
        2L);

    p_curl_easy_setopt(
        easy,
        CURLOPT_FOLLOWLOCATION,
        1L);

    p_curl_easy_setopt(
        easy,
        CURLOPT_TIMEOUT,
        20L);

    p_curl_easy_setopt(
        easy,
        CURLOPT_NOSIGNAL,
        1L);

    p_curl_easy_setopt(
        easy,
        CURLOPT_WRITEFUNCTION,
        http_write);

    p_curl_easy_setopt(
        easy,
        CURLOPT_WRITEDATA,
        &response);

    if (job->post_data) {
        p_curl_easy_setopt(
            easy,
            CURLOPT_POSTFIELDS,
            job->post_data);

        p_curl_easy_setopt(
            easy,
            CURLOPT_POSTFIELDSIZE,
            (long)strlen(job->post_data));

        if (job->content_type) {
            char header[256];

            snprintf(
                header,
                sizeof(header),
                "Content-Type: %s",
                job->content_type);

            headers =
                p_curl_slist_append(
                    headers,
                    header);

            if (headers) {
                p_curl_easy_setopt(
                    easy,
                    CURLOPT_HTTPHEADER,
                    headers);
            }
        }
    }

    fprintf(
        stderr,
        "[RA HTTP] %s\n",
        job->url ?
            job->url :
            "?");

    result =
        p_curl_easy_perform(easy);

    if (result == 0) {
        p_curl_easy_getinfo(
            easy,
            CURLINFO_RESPONSE_CODE,
            &http_status);

        fprintf(
            stderr,
            "[RA HTTP] -> %ld (%zu bytes)\n",
            http_status,
            response.size);
    }
    else {
        fprintf(
            stderr,
            "[RA HTTP] curl %d: %s\n",
            result,
            p_curl_easy_strerror(result));
    }

    {
        rc_api_server_response_t r = {0};

        if (result == 0) {
            r.body =
                response.data ?
                    response.data :
                    "";

            r.body_length =
                response.size;

            r.http_status_code =
                (int)http_status;
        }
        else {
            r.body = "";
            r.body_length = 0;

            r.http_status_code =
                RC_API_SERVER_RESPONSE_CLIENT_ERROR;
        }

        ra_http_deliver(
            job,
            &r,
            serialize_client);
    }

    if (headers)
        p_curl_slist_free_all(headers);

    p_curl_easy_cleanup(easy);

    free(response.data);
}


static void *ra_http_worker(
    void *userdata)
{
    RaHttpJob *job =
        (RaHttpJob *)userdata;

    fprintf(
        stderr,
        "[RA ASYNC] worker started: %s\n",
        job && job->url ?
            job->url :
            "?");

    ra_http_execute(
        job,
        1);

    fprintf(
        stderr,
        "[RA ASYNC] worker finished\n");

    ra_http_job_free(job);

    return NULL;
}


static void ra_server_call(
    const rc_api_request_t *request,
    rc_client_server_callback_t callback,
    void *callback_data,
    rc_client_t *client)
{
    RaHttpJob sync_job;

    char clause[128];

    memset(
        &sync_job,
        0,
        sizeof(sync_job));

    memset(
        clause,
        0,
        sizeof(clause));

    rc_client_get_user_agent_clause(
        client,
        clause,
        sizeof(clause));

    snprintf(
        sync_job.user_agent,
        sizeof(sync_job.user_agent),
        "RGDSPlus-RA/0.1.0 %s",
        clause);

    fprintf(
        stderr,
        "[RA ID] User-Agent: %s\n",
        sync_job.user_agent);

    sync_job.url =
        (char *)(request && request->url ?
            request->url :
            "");

    sync_job.post_data =
        (char *)(request ?
            request->post_data :
            NULL);

    sync_job.content_type =
        (char *)(request ?
            request->content_type :
            NULL);

    sync_job.callback =
        callback;

    sync_job.callback_data =
        callback_data;


    /*
     * Stage 7D.6:
     *
     * ALL RetroAchievements HTTP is asynchronous now.
     *
     * Startup/login/hot-switch callers explicitly wait for their
     * rcheevos completion callbacks instead of relying on the old
     * synchronous server implementation.
     */
    /*
     * Deep-copy everything supplied by rcheevos because the request
     * structure and its strings are not guaranteed to remain valid
     * after this server_call returns.
     */
    RaHttpJob *job =
        calloc(
            1,
            sizeof(*job));

    if (!job) {
        rc_api_server_response_t r = {0};

        r.http_status_code =
            RC_API_SERVER_RESPONSE_CLIENT_ERROR;

        callback(
            &r,
            callback_data);

        return;
    }

    job->url =
        strdup(
            sync_job.url ?
                sync_job.url :
                "");

    if (sync_job.post_data) {
        job->post_data =
            strdup(
                sync_job.post_data);
    }

    if (sync_job.content_type) {
        job->content_type =
            strdup(
                sync_job.content_type);
    }

    snprintf(
        job->user_agent,
        sizeof(job->user_agent),
        "%s",
        sync_job.user_agent);

    job->callback =
        callback;

    job->callback_data =
        callback_data;

    if (!job->url ||
        (sync_job.post_data &&
         !job->post_data) ||
        (sync_job.content_type &&
         !job->content_type)) {

        rc_api_server_response_t r = {0};

        fprintf(
            stderr,
            "[RA ASYNC] request copy failed\n");

        r.http_status_code =
            RC_API_SERVER_RESPONSE_CLIENT_ERROR;

        callback(
            &r,
            callback_data);

        ra_http_job_free(job);

        return;
    }

    pthread_t thread;

    int thread_result =
        pthread_create(
            &thread,
            NULL,
            ra_http_worker,
            job);

    if (thread_result != 0) {
        rc_api_server_response_t r = {0};

        fprintf(
            stderr,
            "[RA ASYNC] pthread_create failed: %s\n",
            strerror(thread_result));

        r.http_status_code =
            RC_API_SERVER_RESPONSE_CLIENT_ERROR;

        callback(
            &r,
            callback_data);

        ra_http_job_free(job);

        return;
    }

    pthread_detach(thread);

    fprintf(
        stderr,
        "[RA ASYNC] HTTP queued: %s\n",
        request && request->url ?
            request->url :
            "?");
}



/* ------------------------------------------------------------------------- */
/* LIVE RetroAchievements memory callback                                    */
/* ------------------------------------------------------------------------- */

static uint32_t ra_read_memory(
    uint32_t address,
    uint8_t *buffer,
    uint32_t num_bytes,
    rc_client_t *client)
{
    (void)client;

    if (!buffer || !num_bytes)
        return 0;

    /*
     * RA $000000-$3FFFFF
     *     -> Nintendo DS 0x02000000-0x023FFFFF
     */
    if (address < MAIN_RAM_SIZE) {
        uint32_t available =
            MAIN_RAM_SIZE - address;

        uint32_t count =
            num_bytes < available ?
            num_bytes : available;

        memcpy(buffer,
               (const void *)(g_main_ram + address),
               count);

        return count;
    }

    /*
     * RA $1000000-$1003FFF
     *     -> ARM9 DTCM
     *
     * Stable DraStic backing:
     *     mapped_memory + 0x410000
     */
    if (address >= RA_DTCM_ADDR &&
        address < RA_DTCM_ADDR + DTCM_SIZE) {

        uint32_t offset =
            address - RA_DTCM_ADDR;

        uint32_t available =
            DTCM_SIZE - offset;

        uint32_t count =
            num_bytes < available ?
            num_bytes : available;

        memcpy(buffer,
               (const void *)(g_dtcm + offset),
               count);

        return count;
    }

    return 0;
}


