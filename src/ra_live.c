static int ra_hardcore_install_early_cheat_probe(void)
{
    uintptr_t address;
    uintptr_t original_target;

    uint32_t found;
    uint32_t branch;

    uint8_t *island;

    long page_size =
        sysconf(_SC_PAGESIZE);

    if (g_ra_early_probe_installed)
        return 1;

    if (!g_ra_launcher_base) {
        fprintf(
            stderr,
            "[RA 7H7] REFUSED: launcher base unavailable\n");

        return 0;
    }

    address =
        g_ra_launcher_base +
        RA_EARLY_CHEAT_PROBE_CALL_RVA;

    found =
        *(volatile uint32_t *)address;

    if (found !=
        RA_EARLY_CHEAT_PROBE_EXPECTED) {

        fprintf(
            stderr,
            "[RA 7H7] REFUSED: "
            "+0x%lx=%08x expected=%08x\n",
            (unsigned long)
                RA_EARLY_CHEAT_PROBE_CALL_RVA,
            found,
            RA_EARLY_CHEAT_PROBE_EXPECTED);

        return 0;
    }

    original_target =
        decode_branch_target(
            address,
            found);

    g_ra_early_probe_original =
        (ra_probe_original_fn)
        (uintptr_t)original_target;

    island =
        (uint8_t *)
        alloc_branch_island(
            address);

    if (!island) {
        fprintf(
            stderr,
            "[RA 7H7] ERROR: "
            "could not allocate early-probe island\n");

        return 0;
    }

    /*
     * The original BL has already made x30 point to +0xABA0.
     *
     * Island:
     *
     *   ldr x16, core_global
     *   str x20, [x16]
     *   ldr x16, fns_global
     *   str x26, [x16]
     *   ldr x16, wrapper
     *   br  x16
     *
     * BR preserves the original x30. The C wrapper calls the
     * original target and then returns directly to +0xABA0.
     */
    *(uint32_t *)(island + 0) =
        0x580000D0U; /* ldr x16, [pc, #24] */

    *(uint32_t *)(island + 4) =
        0xF9000214U; /* str x20, [x16] */

    *(uint32_t *)(island + 8) =
        0x580000D0U; /* ldr x16, [pc, #24] */

    *(uint32_t *)(island + 12) =
        0xF900021AU; /* str x26, [x16] */

    *(uint32_t *)(island + 16) =
        0x580000D0U; /* ldr x16, [pc, #24] */

    *(uint32_t *)(island + 20) =
        0xD61F0200U; /* br x16 */

    *(uint64_t *)(island + 24) =
        (uint64_t)(uintptr_t)
        &g_ra_early_probe_core;

    *(uint64_t *)(island + 32) =
        (uint64_t)(uintptr_t)
        &g_ra_early_probe_drastic_fns;

    *(uint64_t *)(island + 40) =
        (uint64_t)(uintptr_t)
        &ra_early_cheat_probe_wrapper;

    __builtin___clear_cache(
        (char *)island,
        (char *)(island + 48));

    if (page_size <= 0)
        page_size = 4096;

    if (mprotect(
            island,
            (size_t)page_size,
            PROT_READ |
            PROT_EXEC) != 0) {

        fprintf(
            stderr,
            "[RA 7H7] ERROR: "
            "early-probe island mprotect RX failed: %s\n",
            strerror(errno));

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }

    if (!ra_hardcore_encode_bl(
            address,
            (uintptr_t)island,
            &branch)) {

        fprintf(
            stderr,
            "[RA 7H7] ERROR: "
            "early-probe island outside BL range\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }

    if (!ra_hardcore_patch_word(
            address,
            branch)) {

        fprintf(
            stderr,
            "[RA 7H7] ERROR: "
            "could not patch early-probe callsite\n");

        munmap(
            island,
            (size_t)page_size);

        return 0;
    }

    g_ra_early_probe_installed = 1;

    fprintf(
        stderr,
        "[RA 7H7] early cheat probe hook installed "
        "site=+0x%lx island=%p original=%p\n",
        (unsigned long)
            RA_EARLY_CHEAT_PROBE_CALL_RVA,
        island,
        (void *)original_target);

    return 1;
}



