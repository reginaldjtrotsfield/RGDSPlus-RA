/* ============================================================
 * Stage 4: automatic Nintendo DS game hashing
 * ============================================================ */

static uint16_t ra_zip_u16(const uint8_t *p)
{
    return (uint16_t)(
        p[0] |
        ((uint16_t)p[1] << 8));
}

static uint32_t ra_zip_u32(const uint8_t *p)
{
    return
        (uint32_t)p[0] |
        ((uint32_t)p[1] << 8) |
        ((uint32_t)p[2] << 16) |
        ((uint32_t)p[3] << 24);
}

static int ra_ends_with_ci(
    const char *text,
    const char *suffix)
{
    size_t a;
    size_t b;

    if (!text || !suffix)
        return 0;

    a = strlen(text);
    b = strlen(suffix);

    if (a < b)
        return 0;

    text += a - b;

    while (*suffix) {
        char x = *text++;
        char y = *suffix++;

        if (x >= 'A' && x <= 'Z')
            x = (char)(x - 'A' + 'a');

        if (y >= 'A' && y <= 'Z')
            y = (char)(y - 'A' + 'a');

        if (x != y)
            return 0;
    }

    return 1;
}


